type Join<K, P> = K extends string | number ? (P extends string | number ? `${K}.${P}` : never) : never

type Leaves<T> = {
  [K in keyof T]: T[K] extends string ? (K extends string ? K : never) : Join<K, Leaves<T[K]>>
}[keyof T]

/** Clé de traduction en notation pointée (« nav.home », « errors.generic »...). */
export type TranslationKey = Leaves<typeof fr>

export type TranslationVars = Record<string, string | number>

/**
 * Traduit une clé pointée et remplace les variables `{nom}`.
 * Retourne la clé elle-même si elle est introuvable (jamais une erreur en production).
 */
export function t(key: TranslationKey, vars?: TranslationVars): string {
  const segments = key.split('.')
  let node: unknown = fr
  for (const segment of segments) {
    if (node !== null && typeof node === 'object' && segment in (node as Record<string, unknown>)) {
      node = (node as Record<string, unknown>)[segment]
    } else {
      return key
    }
  }
  if (typeof node !== 'string') return key
  if (!vars) return node
  return node.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name]
    return value === undefined ? match : String(value)
  })
}

/**
 * Traduit une clé de statut inconnue à la compilation (valeur venant de la base).
 * Retourne le libellé FR ou la valeur d'origine.
 */
export function statusLabel(status: string, overrides?: Record<string, string>): string {
  const fromOverrides = overrides?.[status]
  if (fromOverrides) return fromOverrides
  const dictionary: Record<string, string> = fr.status
  return dictionary[status] ?? status
}
